import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../server/app.js';
import { config } from '../server/config.js';
import { loadPi } from '../server/pi-adapter.js';
import type { Policy, Run } from '../shared/contracts.js';
import type { ModelRequestReceipt } from '../shared/pi-runtime.js';

test('a restarted host marks an in-flight compaction interrupted without settling its reservation or rewriting history', async () => {
  const before = { ...config };
  Object.assign(config, { apiKey: 'offline-host-restart', provider: 'openai', model: 'gpt-5.6-sol', maxCalls: 4, budgetUsd: 40, reservePerCallUsd: 10 });
  const root = mkdtempSync(join(tmpdir(), 'pi-host-restart-'));
  const child = spawn(process.execPath, ['-e', 'setInterval(()=>{},1000)'], { stdio: 'ignore', windowsHide: true });
  const workerPid = child.pid;
  assert(workerPid);
  child.kill();
  await new Promise<void>(resolve => child.once('exit', () => resolve()));
  const app = createApp({ dataDir: join(root, 'data'), password: 'host-restart-password', schedule: false });
  try {
    const project = app.service.createProject('宿主重启');
    const policy: Policy = { version: 8, projectId: project.id, toolNames: [], allowModel: true, modelBinding: app.modelAccess.settings().binding, maxCalls: 4, maxCostUsd: 40, reservePerCallUsd: 10, maxOutputTokens: 256, timeoutMs: 30000, piRuntime: { schemaVersion: 1, configurationRevision: 0, requestedThinkingLevel: 'off', thinkingLevel: 'off', autoCompaction: true } };
    const cwd = join(root, 'data', 'workspaces', project.id); const sessions = join(root, 'data', 'sessions', project.id); mkdirSync(cwd, { recursive: true }); mkdirSync(sessions, { recursive: true });
    const pi = await loadPi(); const manager = pi.SessionManager.create(cwd, sessions);
    manager.appendMessage({ role: 'user', content: 'HOST_RESTART_SOURCE', timestamp: Date.now() });
    const seeded = app.service.submit(project.id, 'seed', 'seed', 'pi', policy, [], undefined, { view: 'project' }, null).run;
    app.service.transition(seeded.id, 'running');
    const saved = app.store.get<Run>('run', seeded.id);
    app.store.update<Run>('run', saved.id, saved.revision, { sessionPath: manager.getSessionFile(), sessionId: manager.getSessionId() });
    app.store.create<import('../shared/contracts.js').SessionBinding>('session_binding', { id: `session:${seeded.id}`, projectId: project.id, runId: seeded.id, taskId: seeded.taskId, policyVersion: policy.version, model: policy.modelBinding!.model, authKind: policy.modelBinding!.kind, sessionId: manager.getSessionId(), sessionPath: manager.getSessionFile()!, piVersion: '1.0.3', cwd });
    app.service.transition(seeded.id, 'completed');
    const sourceBytes = readFileSync(manager.getSessionFile()!);
    const compact = app.service.submit(project.id, 'compact', 'compact', 'pi', policy, [], undefined, { view: 'project' }, seeded.id, undefined, 'compact').run;
    app.service.transition(compact.id, 'running');
    const running = app.store.get<Run>('run', compact.id);
    app.store.update<Run>('run', running.id, running.revision, { startedAt: new Date().toISOString(), leaseUntil: 0, workerPid, calls: 1, reservedUsd: 10, spentUsd: 0, usage: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, totalTokens: 0, complete: false } });
    app.store.create<ModelRequestReceipt>('model_request', { id: `${compact.id}:1`, schemaVersion: 1, projectId: project.id, runId: compact.id, taskId: compact.taskId, callNumber: 1, purpose: 'compaction', state: 'reserved', reservedUsd: 10 });
    app.scheduler.tick();
    const stopped = app.store.get<Run>('run', compact.id);
    assert.equal(stopped.status, 'interrupted');
    assert.match(stopped.error ?? '', /执行失联/);
    assert.equal(stopped.reservedUsd, 10);
    assert.equal(stopped.spentUsd, 0);
    assert.notEqual(stopped.usage?.complete, true);
    const receipt = app.store.list<ModelRequestReceipt>('model_request').find(item => item.runId === compact.id)!;
    assert.equal(receipt.purpose, 'compaction');
    assert.equal(receipt.state, 'reserved');
    assert.equal(receipt.costUsd, undefined);
    assert.equal(receipt.usage, undefined);
    assert.deepEqual(readFileSync(manager.getSessionFile()!), sourceBytes);
    assert.throws(() => app.service.retry(compact.id, 'before-ack'), /对账/);
    app.scheduler.acknowledge(compact.id);
    const resumed = app.service.retry(compact.id, 'after-ack');
    assert.equal(resumed.status, 'queued');
    assert.equal(resumed.sessionAction, 'compact');
    assert.equal(app.store.list<ModelRequestReceipt>('model_request').find(item => item.id === receipt.id)?.state, 'reserved');
    assert.deepEqual(readFileSync(manager.getSessionFile()!), sourceBytes);
    mkdirSync('output/dev-evidence/pi-parity/compaction-host-restart', { recursive: true });
    writeFileSync('output/dev-evidence/pi-parity/compaction-host-restart/report.json', JSON.stringify({ sourceBytes: sourceBytes.length, receiptState: receipt.state, reservedUsd: stopped.reservedUsd, resumed: resumed.status }, null, 2));
  } finally { await app.close(); Object.assign(config, before); }
});
