import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { createHash, randomUUID } from 'node:crypto';
import { mkdirSync, mkdtempSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { CanvasService } from '../server/canvas-service.js';
import { CanvasBindings } from '../server/canvas-bindings.js';
import { CanvasApi } from '../server/canvas-api.js';
import { Store, AppError } from '../server/store.js';
import type { Project } from '../shared/contracts.js';
import { encodeCanvasPackage } from '../apps/canvas/local/canvas-package.mjs';

test('directory and output ids stay inside the project that reserved them',async()=>{
  const root=mkdtempSync(join(tmpdir(),'canvas-resources-'));
  const directory=mkdtempSync(join(tmpdir(),'canvas-resource-dir-'));
  const store=new Store(join(root,'host.sqlite'));
  const service=new CanvasService({entry:resolve('apps/canvas/local/desktop-entry.mjs'),directory:join(root,'canvas'),origin:'http://private.invalid'});
  const bindings=new CanvasBindings(store),api=new CanvasApi(bindings);
  const a=store.create<Project>('project',{name:'A',description:'',archived:false}),b=store.create<Project>('project',{name:'B',description:'',archived:false});
  let origin='';
  const server=createServer((req,res)=>{void api.handle(req,res,req.url!,service.transport!,origin).catch(error=>{res.writeHead(error instanceof AppError?error.status:500,{'Content-Type':'application/json'});res.end(JSON.stringify({error:error instanceof Error?error.message:String(error)}));});});
  try{
    await service.start();await new Promise<void>(done=>server.listen(0,'127.0.0.1',done));
    origin=`http://127.0.0.1:${(server.address() as {port:number}).port}`;
    const request=(path:string,project:string,data?:unknown)=>fetch(origin+path,{method:data===undefined?'GET':'POST',headers:{Origin:origin,'Content-Type':'application/json','X-Canvas-Project':project},body:data===undefined?undefined:JSON.stringify(data)});
    const created=await request('/mounts',a.id,{path:directory});
    assert.equal(created.status,200);
    const mount=await created.json() as {id:string;canvasId:string};
    assert.equal(bindings.find(mount.canvasId)?.operationId,mount.canvasId);
    assert.equal((await request(`/mounts/${mount.id}/files`,b.id)).status,403);
    assert.equal((await request('/mounts',b.id,{path:directory})).status,403);
    assert.equal(bindings.find(mount.canvasId)?.projectId,a.id);
    assert.equal((await request(`/mounts/${mount.id}/files`,a.id)).status,200);
    assert.deepEqual((await (await request('/mounts',b.id)).json()),[]);
    const nodeId=randomUUID(),operationId=randomUUID();
    const scene=readFileSync('apps/canvas/local/fixtures/revision-1.fig').toString('base64');
    const saved=await request(`/canvases/${mount.canvasId}`,a.id,{operationId,expectedRevision:0,metadata:{formatVersion:1,name:'Directory',outputSourceNodeIds:[nodeId]},sceneBase64:scene});
    assert.equal(saved.status,200);
    assert.equal(bindings.authorize(a.id,mount.canvasId).operationId,operationId);
    const output={operationId:randomUUID(),canvasId:mount.canvasId,nodeId,sourceRevision:1,mountId:mount.id,name:'成果.txt',contentBase64:Buffer.from('project-a').toString('base64')};
    assert.equal((await request('/outputs',b.id,output)).status,403);
    assert.equal((await request('/outputs',a.id,output)).status,200);
    assert.equal((await request(`/outputs/${output.operationId}/cancel`,b.id,{})).status,403);
    assert.equal((await request(`/outputs/${output.operationId}/commit`,a.id,{})).status,200);
    assert.equal(readFileSync(join(directory,'成果.txt'),'utf8'),'project-a');
    const stolen=await request('/file-targets/preview',b.id,{path:join(directory,'成果.txt')});
    assert.equal(stolen.status,200);
    assert.equal((await request('/file-targets/confirm',b.id,{token:(await stolen.json()).token})).status,403);
    assert.equal(bindings.find(mount.canvasId)?.projectId,a.id);
    const folder=mkdtempSync(join(tmpdir(),'canvas-resource-file-'));writeFileSync(join(folder,'note.txt'),'note');
    const preview=await request('/file-targets/preview',a.id,{path:join(folder,'note.txt')});
    assert.equal(preview.status,200);
    const token=(await preview.json()).token as string;
    assert.equal((await request('/file-targets/confirm',b.id,{token})).status,403);
    const confirmed=await request('/file-targets/confirm',a.id,{token});
    assert.equal(confirmed.status,200);
    const claimed=(await confirmed.json()).mountId as string;
    const claimedCanvas=(await (await request('/mounts',a.id)).json() as Array<{id:string;canvasId:string}>).find(row=>row.id===claimed)?.canvasId;
    assert.equal(bindings.find(claimedCanvas!)?.projectId,a.id);
    assert.equal((await request(`/mounts/${claimed}/files`,b.id)).status,403);
    const packageScene=readFileSync('apps/canvas/local/fixtures/revision-1.fig');
    const imported=randomUUID(),packageId=randomUUID();
    const packed=encodeCanvasPackage({canvasId:imported,revisions:[{canvasId:imported,revision:1,sceneHash:createHash('sha256').update(packageScene).digest('hex'),scene:packageScene,metadata:{formatVersion:1,name:'Imported'},createdAt:'2026-10-16T00:00:00.000Z'}],layout:{formatVersion:1,panels:{layers:true,properties:true}},references:{formatVersion:1,mounts:[],files:[]}});
    const upload=async(project:string,id:string,bytes:Buffer)=>{
      const response=await fetch(origin+`/package-imports/${id}`,{method:'POST',headers:{Origin:origin,'Content-Type':'application/octet-stream','X-Canvas-Project':project},body:new Uint8Array(bytes)});
      return {status:response.status,text:await response.text()};
    };
    const denied=await upload(b.id,randomUUID(),encodeCanvasPackage({canvasId:mount.canvasId,revisions:[{canvasId:mount.canvasId,revision:1,sceneHash:createHash('sha256').update(packageScene).digest('hex'),scene:packageScene,metadata:{formatVersion:1,name:'Stolen'},createdAt:'2026-10-16T00:00:00.000Z'}],layout:{formatVersion:1,panels:{layers:true,properties:true}},references:{formatVersion:1,mounts:[],files:[]}}));
    assert.equal(denied.status,403,denied.text);
    const accepted=await upload(a.id,packageId,packed);
    assert.equal(accepted.status,200,accepted.text);
    assert.equal((await request(`/package-imports/${packageId}/resume`,b.id,{})).status,403);
    assert.equal((await request(`/package-imports/${packageId}/resume`,a.id,{})).status,200);
    assert.equal(bindings.authorize(a.id,imported).state,'ready');
    assert.equal((await request(`/canvases/${imported}`,b.id)).status,403);
    const root=mkdtempSync(join(tmpdir(),'canvas-child-root-')),child=join(root,'child');
    mkdirSync(child);writeFileSync(join(child,'asset.txt'),'old');
    const parent=await (await request('/mounts',a.id,{path:root})).json() as {id:string};
    assert.equal((await request(`/mounts/${parent.id}/scan`,a.id,{})).status,200);
    const entries=(await (await request(`/mounts/${parent.id}/files`,a.id)).json()).entries as Array<{id:string;kind:string}>;
    const folderEntry=entries.find(entry=>entry.kind==='directory');
    assert.ok(folderEntry);
    const opened=await (await request(`/mounts/${parent.id}/files/${folderEntry.id}/open`,a.id,{})).json() as {canvasId:string};
    renameSync(child,join(tmpdir(),`old-child-${randomUUID()}`));mkdirSync(child);writeFileSync(join(child,'asset.txt'),'new');
    const owned=await request(`/mounts/${parent.id}/files/${folderEntry.id}/replacement-preview`,a.id,{});
    assert.equal(owned.status,200,await owned.clone().text());
    const ownedPreview=await owned.json() as {token:string;childCanvasId:string};
    assert.equal(ownedPreview.childCanvasId,opened.canvasId);
    assert.equal((await request(`/mounts/${parent.id}/files/${folderEntry.id}/replacement-confirm`,b.id,{token:ownedPreview.token})).status,403);
    store.db.prepare('UPDATE canvas_bindings SET project_key=? WHERE canvas_id=?').run(b.id,opened.canvasId);
    assert.equal((await request(`/mounts/${parent.id}/files/${folderEntry.id}/replacement-preview`,a.id,{})).status,403);
    const moved=mkdtempSync(join(tmpdir(),'canvas-relink-'));
    const relink=await request(`/mounts/${mount.id}/relink-preview`,a.id,{path:moved});
    assert.equal(relink.status,200,await relink.clone().text());
    const relinkToken=(await relink.json()).token as string;
    assert.equal((await request(`/mounts/${mount.id}/relink-preview`,b.id,{path:moved})).status,403);
    assert.equal((await request(`/mounts/${mount.id}/relink-confirm`,b.id,{token:relinkToken})).status,403);
    assert.equal((await request(`/mounts/${mount.id}/relink-confirm`,a.id,{token:relinkToken})).status,200);
    const foreignRoot=mkdtempSync(join(tmpdir(),'canvas-foreign-child-')),foreignChild=join(foreignRoot,'child');
    mkdirSync(foreignChild);
    const foreignMount=await (await request('/mounts',b.id,{path:foreignChild})).json() as {id:string;path:string;canvasId:string};
    const foreignParent=await (await request('/mounts',a.id,{path:foreignRoot})).json() as {id:string};
    assert.equal((await request(`/mounts/${foreignParent.id}/scan`,a.id,{})).status,200);
    const foreignEntries=(await (await request(`/mounts/${foreignParent.id}/files`,a.id)).json()).entries as Array<{id:string;kind:string}>;
    const foreignFolder=foreignEntries.find(entry=>entry.kind==='directory');
    assert.ok(foreignFolder);
    assert.equal((await request(`/mounts/${foreignParent.id}/files/${foreignFolder.id}/open`,a.id,{})).status,403);
    renameSync(foreignChild,join(foreignRoot,'moved'));
    assert.equal((await request(`/mounts/${foreignParent.id}/scan`,a.id,{})).status,200);
    const movedEntries=(await (await request(`/mounts/${foreignParent.id}/files`,a.id)).json()).entries as Array<{id:string;kind:string;path:string}>;
    const movedFolder=movedEntries.find(entry=>entry.kind==='directory'&&entry.path==='moved');
    assert.ok(movedFolder);
    assert.equal((await request(`/mounts/${foreignParent.id}/files/${movedFolder.id}/open`,a.id,{})).status,403);
    assert.equal((await request('/mounts',a.id,{path:join(foreignRoot,'moved')})).status,409);
    const foreignRows=await (await request('/mounts',b.id)).json() as Array<{id:string;path:string;canvasId:string}>;
    assert.equal(foreignRows.find(row=>row.id===foreignMount.id)?.path,foreignChild);
    assert.equal(bindings.find(foreignMount.canvasId)?.projectId,b.id);
  }finally{server.closeAllConnections();await new Promise<void>(done=>server.close(()=>done()));await service.dispose();store.db.close();}
});
